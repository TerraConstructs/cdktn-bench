"""The Python verifier: `tests/tiers.py` (mechanism) and `tests/verify.py`
(one task's configuration), emitted by gen.py in place of the two bash scripts.

`tiers.py` is byte-identical in every task directory, like `ops.py`; everything
that varies between specs, arms and steps -- the toolchain command lines, the
tier-1 engine and query, every reason string a live tier can write -- is a
literal in the generated `verify.py`. That split is what makes the port
checkable: one mechanism to review, and a per-task config a reader can diff
against the spec.

`tests/test.sh` and `tests/static_tiers.sh` stay on disk as shims, because
harbor executes the first path and every hand-authored `solution/**/solve.sh`
ends by running the second (gen.py::build_test_sh_shim explains both).
"""

