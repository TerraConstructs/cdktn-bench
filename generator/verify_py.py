def tier_0(cfg, artifact, norm_status="OK"):
    """1 iff every applicable structural assert held. A tier-0 that could not
    run at all reports 0, which the reward gate maps to 0.0 -- never a silent
    pass. A normaliser that did not produce a document is one of those: the
    asserts address root_module.resources, so grading the raw plan of a
    module-shaped solution would read an empty resource set and report every
    assert unresolvable with no reason a transcript reader could act on."""
    if norm_status != "OK":
        tee(
            "tier0-engine-error",
            list(NORMALISE_FAILED_LINES) + read_lines("plan-normaliser.log"),
        )
        return 0
    if cfg["engine"] == "rego":
        return _tier0_rego(cfg, artifact)
    if not have("python3") or not have("jq"):
        tee("tier0-unavailable", list(TIER0_TOOLS_MISSING_LINES))
        return 0
    sys.stdout.flush()
    rc = subprocess.run(["python3", str(DIR / "tier0.py"), str(artifact)]).returncode
    return 0 if rc else 1


def _tier0_rego(cfg, artifact):
    """One `opa eval` returns the whole tier-0 report; its FIRST line is the
    verdict and is compared as a whole string, because the log lines after it
    quote artifact values the agent controls."""
    if not have("opa"):
        tee("tier0-unavailable", list(TIER0_OPA_MISSING_LINES))
        return 0
    argv = ["opa", "eval", "-f", "raw", "-I", "-d", str(DIR / "tier0.rego"), cfg["query"]]
    sys.stdout.flush()
    with open(artifact, "rb") as src, open(LOGS / "tier0-opa-stderr.log", "wb") as log:
        p = subprocess.run(argv, stdin=src, stdout=subprocess.PIPE, stderr=log)
    if p.returncode:
        tee(
            "tier0-engine-error",
            list(TIER0_OPA_ABORT_LINES) + read_lines("tier0-opa-stderr.log"),
        )
        return 0
    text = p.stdout.decode(errors="replace").rstrip("\\n")
    out(text)
    return 1 if text.split("\\n", 1)[0] == "TIER0_PASS=1" else 0


