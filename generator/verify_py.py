def aws_preflight():
    """A cheap read-only call BEFORE any toolchain command, so a broken
    credential chain is never charged to a solution. False leaves the
    aws-unavailable marker behind, which is what main()'s short-circuit keys off
    to VOID the row before any gating block can turn it into a 0.0."""
    region()
    for name in ("aws-unavailable", "aws-unavailable.json"):
        try:
            (LOGS / name).unlink()
        except OSError:
            pass
    try:
        rc = subprocess.run(
            ["aws", "sts", "get-caller-identity"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        ).returncode
    except OSError:
        rc = 127
    if rc == 0:
        return True
    tee("aws-unavailable", list(AWS_UNAVAILABLE_LINES))
    write_json(
        "aws-unavailable.json",
        {
            "outcome": "run_invalid",
            "status": "run_invalid",
            "reason": "aws sts get-caller-identity failed -- no working AWS "
            "credentials in this environment",
        },
    )
    return False


