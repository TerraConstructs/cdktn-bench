def normalised_plan_path(artifact):
    """`<artifact>.normalised.json` beside the artifact, written once per
    verifier run and reused by every tier after.

    The RAW artifact is left exactly as the toolchain wrote it: the falsifiability
    collector and the blast-radius read it, and `resource_changes` -- which the
    normaliser does not touch -- is what they read it for.
    """
    key = str(artifact)
    if key not in NORMALISED:
        source = Path(artifact)
        try:
            plan = json.loads(source.read_text())
        except ValueError as exc:
            raise NormaliseError("%s is not JSON: %s" % (artifact, exc))
        target = source.parent / (source.stem + ".normalised.json")
        # Key order is the RAW plan's, not sorted: the `_hcl` merge re-dumps
        # this document in the order it reads it, and gates/hcl_merge_bytes.py
        # compares those bytes against a baseline run over the raw plan.
        target.write_text(json.dumps(normalise_plan(plan), indent=2) + "\\n")
        NORMALISED[key] = target
    return NORMALISED[key]


# --- the module-source rule (hcl_modules only) ------------------------------

MODULE_SOURCE_LABEL = "module sources"
MODULE_SOURCE_DENIED_LINES = (
    "a call the ROOT module makes resolves from somewhere other than",
    "the module registry this environment serves. Every root `module`",
    "block on this arm must name a registry source under",
    "%s; a local path (a copy of the vendored",
    "tree, or a hand-written module inside the workspace) is not one.",
    "A call an INSTALLED module makes inside its own tree is exempt --",
    "those are legitimately relative. Offending call(s):",
)


def module_source_denials(rule):
    """The root `module` calls whose Source is not a registry source, read off
    `.terraform/modules/modules.json` -- the manifest `terraform init` writes,
    which records where each installed call actually came from.

    A `Key` of "" is the root module itself and a `Key` containing a dot is a
    call made INSIDE an installed module (ecs -> ./modules/cluster), so both are
    exempt: applied to every entry the rule would refuse the vendored modules'
    own submodules. Identical scoping to
    arms/hcl-modules/environment/preflight.sh::assert_root_calls_are_registry_sources,
    which is what stops the image's own fixtures tripping this deny.

    A manifest that does not exist means `init` installed no module at all,
    which is a configuration with no `module` block in it -- nothing to deny.
    """
    manifest = PROJECT / rule["manifest"]
    if not manifest.is_file():
        return []
    try:
        entries = (json.loads(manifest.read_text()) or {}).get("Modules") or []
    except ValueError as exc:
        return ["%s is not JSON: %s" % (manifest, exc)]
    bad = []
    for entry in entries:
        key = entry.get("Key") or ""
        source = entry.get("Source") or ""
        if key == "" or "." in key:
            continue
        if source.startswith(rule["registry_prefix"]):
            continue
        bad.append("module %r -> source %r" % (key, source))
    return bad


def module_sources_ok(cfg):
    """False having already reported, for an arm that declares the rule and a
    workspace that breaks it. Reported as a named toolchain-shaped step --
    `<LABEL> FAILED`, reward 0.0 -- because it is decided before any assert
    runs, exactly like a failed `terraform plan`."""
    rule = cfg.get("module_sources")
    if not rule:
        return True
    out("", "== %s: %s ==" % (MODULE_SOURCE_LABEL, rule["manifest"]))
    bad = module_source_denials(rule)
    if not bad:
        return True
    lines = [line % rule["registry_prefix"] if "%s" in line else line
             for line in MODULE_SOURCE_DENIED_LINES]
    (LOGS / "module-source-denied").write_text("\\n".join(lines + bad) + "\\n")
    out(*lines)
    out(*bad)
    out("%s FAILED" % MODULE_SOURCE_LABEL.upper())
    return False


def normalise_artifact(cfg, artifact):
    """(status, artifact-to-grade). Any status but OK means no tier may grade
    the document, exactly as an HCL pre-parse failure does: the tiers address
    `root_module.resources`, so grading an unnormalised module-shaped plan
    reads an empty resource set and reports a correct solution as wrong."""
    if not cfg.get("normalise_plan"):
        return "OK", artifact
    try:
        return "OK", normalised_plan_path(artifact)
    except (NormaliseError, OSError, RecursionError) as exc:
        (LOGS / "plan-normaliser.log").write_text("%s\\n" % exc)
        return "ENGINE_ERROR", artifact


# --- persisting the graded documents ----------------------------------------


def persist_artifacts(artifact, graded):
    """Copy the graded plan (or template) into harbor's collection directory.

    Blast radius (gates/blast_radius.py) counts `resource_changes[]`, which only
    the plan carries and which nothing else the trial keeps can reconstruct -- so
    a row's blast radius exists only if the document that produced it was kept.
    Both the RAW artifact and the normalised copy are kept: tier 0 and tier 1
    graded the normalised one, and the raw one is what the counts are read from.

    Best-effort by contract: a copy that fails is reported on stdout and changes
    no reward. The artifact is the evidence for a measurement, never a grading
    input, and a full disk must not turn a correct solution into a 0.0.
    """
    try:
        ARTIFACTS.mkdir(parents=True, exist_ok=True)
        for src in dict.fromkeys([Path(artifact), Path(graded)]):
            if src.is_file():
                shutil.copyfile(src, ARTIFACTS / src.name)
    except OSError as exc:
        out("ARTIFACT NOT PERSISTED: %s" % exc)


