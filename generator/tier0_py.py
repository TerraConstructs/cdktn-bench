"""The tier-0 driver the generator emits: `tests/ops.py` and `tests/tier0.py`.

`tests/ops.py` is one fixed file -- the op table of specs/SCHEMA.md §4.2 and
the three-valued outcome -- byte-identical in every arm's `tests/` and in a
brownfield task's `pre_invoke/`. `tests/tier0.py` is per arm (per step, where a
spec declares steps): the assert table, one tuple per applicable tier-"0"
`structural_assert`, with the declared JSONPath above each entry so a reviewer
reads the spec's own question beside the jq filter it compiled to.

The jq filter strings are produced by generator/jsonpath_jq.py and are carried
into the table character for character -- jq stays the path language, Python
only drives it and applies the op.
"""

from __future__ import annotations

import json
import textwrap
from dataclasses import dataclass


@dataclass(frozen=True)
class Tier0Entry:
    """One tier-"0" structural_assert, projected for one arm."""

    name: str
    jsonpath: str
    jq_filter: str
    op: str
    expected: object


# The emitted tests/ops.py. One owner, two destinations (tests/ and, for a
# brownfield task, pre_invoke/), so the seed proof and tier-0 can never
# disagree about what `set_eq` means.
#
# Stdlib only and no f-strings in the emitted text: it runs under whatever
# python3 the arm image ships, beside a jq it drives as a subprocess, and
# nothing else.
OPS_PY = r'''#!/usr/bin/env python3
"""tests/ops.py -- GENERATED by generator/gen.py. Do not hand-edit; regenerate
the owning scenario instead. Byte-identical in every arm's tests/ and in a
brownfield task's pre_invoke/.

The tier-0 op table (specs/SCHEMA.md §4.2) applied to the nodes jq resolves
from one compiled filter. tests/tier0.py carries this arm's assert table and
calls main(); a brownfield pre_invoke.sh calls `--one` once per declared live
assert against an `aws` CLI response.

THE OUTCOME IS THREE-VALUED, and that is the property this file exists to
protect -- "the proof did not run" is not "the artifact is wrong":

  held         exit 0   the assert resolved and held
  contradicted exit 1   the assert resolved and was contradicted -- a verdict
  unresolvable exit 2   the question could not be asked -- NOT a verdict

A jq error, a missing jq, an op this table does not define, an `expected` of
the wrong JSON type and a pattern Python's `re` refuses are all unresolvable.
Regex is Python `re`, the single tier-0 flavour (DECISIONS.md Amendment 43).
"""

import json
import os
import re
import subprocess
import sys
import tempfile

HELD = "held"
CONTRADICTED = "contradicted"
UNRESOLVABLE = "unresolvable"

# The exit status each outcome maps to. Every caller reads these three codes:
# tier0.py aggregates them, pre_invoke.sh dispatches on them, and anything
# outside the set is a harness fault the caller must not read as a verdict.
EXIT_CODE = {HELD: 0, CONTRADICTED: 1, UNRESOLVABLE: 2}


class Unresolvable(Exception):
    """The question could not be asked; the message is the operator's reason."""


def _json_key(value):
    """A canonical stand-in for `value` under JSON equality, which Python `==`
    is not.

    JSON keeps `true` and `1` distinct types where Python reads them as equal,
    and treats `1` and `1.0` as one number. Containers are rewritten
    recursively because either mismatch can sit well below the top level --
    inside a resolved policy statement's `Action` list, say.
    """
    if isinstance(value, bool):
        return ("bool", value)
    if isinstance(value, float) and value.is_integer():
        return int(value)
    if isinstance(value, dict):
        return dict((k, _json_key(v)) for k, v in value.items())
    if isinstance(value, list):
        return [_json_key(v) for v in value]
    return value


def _eq(left, right):
    return _json_key(left) == _json_key(right)


def _value_set(values):
    """`set_eq`'s set, keyed by canonical JSON. A plain `set()` raises
    TypeError on an object- or list-valued node, which is a crash where jq's
    own `unique` returns a set."""
    return set(json.dumps(_json_key(v), sort_keys=True) for v in values)


def _flatten_once(values):
    """`in` and `set_eq` flatten EXACTLY one level: an IAM `Action` is a bare
    string on one statement and a list of strings on the next, and both forms
    have to reach the same membership test."""
    flat = []
    for value in values:
        if isinstance(value, list):
            flat.extend(value)
        else:
            flat.append(value)
    return flat


def _contains_one(value, expected):
    """`contains` on one node: a LITERAL substring on a string, membership on
    a list, equality otherwise.

    Never a regex. jq's `test($e)` would read an expected of
    "ec2.amazonaws.com" as a pattern whose "." matches any character, so the
    actual string "ec2Xamazonaws.com" would PASS a role-trust check -- a
    security-relevant false pass, not a theoretical one.
    """
    if isinstance(value, list):
        return any(_eq(element, expected) for element in value)
    if isinstance(value, str):
        return isinstance(expected, str) and expected in value
    return _eq(value, expected)


def _pattern(op, expected):
    if not isinstance(expected, str):
        raise Unresolvable(
            "op %s needs a string `expected`, got %s (UNRESOLVABLE, not "
            "contradicted)" % (op, type(expected).__name__)
        )
    try:
        return re.compile(expected)
    except re.error as exc:
        raise Unresolvable(
            "op %s cannot compile expected=%s under Python re: %s (UNRESOLVABLE, "
            "not contradicted)" % (op, json.dumps(expected), exc)
        )


def _expected_list(op, expected):
    if not isinstance(expected, list):
        raise Unresolvable(
            "op %s is defined over a list `expected`, got %s (UNRESOLVABLE, not "
            "contradicted)" % (op, type(expected).__name__)
        )
    return expected


def resolve(jq_filter, artifact_path):
    """The nodes one compiled filter resolves to: (jq's own compact output,
    the parsed list).

    `map(select(. != null))` drops JSON null. jq's plain field access returns
    null for a key that is simply absent rather than raising or producing no
    output, so an uncollected `[ .Foo ]` over N matched objects none of which
    has Foo resolves to `[null, null, ...]` -- length N, not 0 -- and
    `not_exists` could never pass on the genuinely-absent-field case it exists
    to check.
    """
    program = "[ %s ] | map(select(. != null))" % jq_filter
    try:
        proc = subprocess.run(
            ["jq", "-c", program, artifact_path],
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            universal_newlines=True,
        )
    except OSError as exc:
        raise Unresolvable(
            "could not run jq: %s (UNRESOLVABLE, not contradicted)" % exc
        )
    if proc.returncode != 0:
        raise Unresolvable(
            "jq query error (UNRESOLVABLE, not contradicted): %s"
            % proc.stderr.rstrip("\n")
        )
    try:
        nodes = json.loads(proc.stdout)
    except ValueError as exc:
        raise Unresolvable(
            "jq exited 0 but its output is not JSON: %s (UNRESOLVABLE, not "
            "contradicted)" % exc
        )
    if not isinstance(nodes, list):
        raise Unresolvable(
            "jq returned %s where the collected form `[ ... ]` can only be a "
            "list (UNRESOLVABLE, not contradicted)" % type(nodes).__name__
        )
    return proc.stdout.rstrip("\n"), nodes


def apply_op(op, expected, nodes):
    """Apply one §4.2 op to the resolved nodes. Raises Unresolvable for an op
    this table does not define and for an `expected` the op cannot use."""
    if op == "exists":
        return len(nodes) > 0
    if op == "not_exists":
        return len(nodes) == 0
    if op == "eq":
        # "the (single) resolved value equals expected": 0 or >1 nodes is a
        # failure, never "pick one" -- the ambiguity is itself the failure.
        return len(nodes) == 1 and _eq(nodes[0], expected)
    if op == "in":
        flat = _flatten_once(nodes)
        allowed = _expected_list(op, expected)
        return len(flat) > 0 and all(
            any(_eq(value, candidate) for candidate in allowed) for value in flat
        )
    if op == "contains":
        return len(nodes) >= 1 and any(_contains_one(v, expected) for v in nodes)
    if op == "regex":
        pattern = _pattern(op, expected)
        return len(nodes) >= 1 and any(
            isinstance(v, str) and pattern.search(v) is not None for v in nodes
        )
    if op == "set_eq":
        # The "and nothing else" op. `in`/`contains` pass as long as the
        # correct value is PRESENT, so a trust policy that correctly lists
        # ec2.amazonaws.com and ALSO an unintended second principal passes
        # both -- one correct value masking an arbitrarily bad extra one.
        allowed = _expected_list(op, expected)
        return _value_set(_flatten_once(nodes)) == _value_set(allowed)
    if op == "absent_or_eq":
        # "either the implied default was left unset, or it was written out
        # explicitly": `not_exists` alone rejects `tier = "Standard"` and `eq`
        # alone rejects the omitted form, and both forms are correct.
        return len(nodes) == 0 or (len(nodes) == 1 and _eq(nodes[0], expected))
    if op == "not_regex":
        # Literal negation of `regex`'s per-value search, except that 0
        # resolved nodes vacuously HOLDS: nothing is present to violate a
        # "must never contain X" rule.
        pattern = _pattern(op, expected)
        return not any(
            isinstance(v, str) and pattern.search(v) is not None for v in nodes
        )
    raise Unresolvable("unknown op %s (UNRESOLVABLE, not contradicted)" % op)


def check(name, jq_filter, op, expected, artifact_path):
    """One assert: (outcome, resolved, detail).

    `resolved` is jq's own compact output, verbatim, so a FAIL line shows the
    operator the same text a hand-run `jq -c` would; it is None when the path
    never resolved. `detail` is the reason, and is empty unless the outcome
    needs one.
    """
    resolved = None
    try:
        resolved, nodes = resolve(jq_filter, artifact_path)
        held = apply_op(op, expected, nodes)
    except Unresolvable as exc:
        return UNRESOLVABLE, resolved, str(exc)
    if held:
        return HELD, resolved, ""
    return (
        CONTRADICTED,
        resolved,
        "op=%s expected=%s resolved=%s" % (op, json.dumps(expected), resolved),
    )


def report(name, outcome, detail):
    """The per-assert line gates/emit_result.py parses out of
    verifier/test-stdout.txt, keyed on the structural_assert name."""
    if outcome == HELD:
        print("  PASS [%s]" % name)
    else:
        print("  FAIL [%s]: %s" % (name, detail))


def run_one(name, jq_filter, op, expected, artifact_path):
    """One assert, reported and reduced to its exit status. Every exception is
    an unresolvable: a traceback escaping here would exit 1 and be read by
    pre_invoke.sh's dispatch as a contradicted fact about a real AWS account.
    """
    try:
        outcome, _resolved, detail = check(name, jq_filter, op, expected, artifact_path)
    except Exception as exc:  # noqa: BLE001 - see the docstring
        outcome, detail = UNRESOLVABLE, (
            "%s while evaluating the assert: %s (UNRESOLVABLE, not contradicted)"
            % (type(exc).__name__, exc)
        )
    report(name, outcome, detail)
    return EXIT_CODE[outcome]


def main(asserts, artifact_path):
    """Every assert in one table, in declaration order. Exit 0 iff all held.

    No short-circuit: tier 0 reports every assert's own verdict, because a
    trial's transcript is read for WHICH catch fired, not just whether one
    did. The status returned is the WORST outcome's code, so an unresolvable
    assert dominates a contradicted one -- a run whose proof did not run is
    worth less than one that ran and found a fault.
    """
    worst = 0
    for name, jq_filter, op, expected in asserts:
        worst = max(worst, run_one(name, jq_filter, op, expected, artifact_path))
    return worst


# The exact, whole line `--selftest` prints on success. A caller compares its
# whole stdout against this rather than reading the exit status: a truncated
# upload is a file that ignores its own argv and exits 0, so "exited 0" proves
# nothing and only an answer this file had to compute does.
SELFTEST_OK = "OPS_SELFTEST_OK"


def _selftest():
    """Prove this file is the real driver and that jq runs, before a caller
    spends anything against a real account on the strength of it.

    One assert per outcome, so the three-valued contract itself is what is
    proven rather than merely that the file loads.
    """
    handle, path = tempfile.mkstemp(suffix=".json", prefix="ops-selftest-")
    try:
        with os.fdopen(handle, "w") as fh:
            fh.write('{"a": "x"}')
        cases = (
            ("held", ".a", "eq", "x", HELD),
            ("contradicted", ".a", "eq", "y", CONTRADICTED),
            ("unresolvable", ".a", "frobnicate", None, UNRESOLVABLE),
        )
        for label, jq_filter, op, expected, want in cases:
            got, _resolved, detail = check(label, jq_filter, op, expected, path)
            if got != want:
                print(
                    "ops.py selftest: %s came out %s, wanted %s (%s)"
                    % (label, got, want, detail),
                    file=sys.stderr,
                )
                return 1
    finally:
        os.unlink(path)
    print(SELFTEST_OK)
    return 0


def _usage():
    print(
        "usage: ops.py --selftest\n"
        "       ops.py --one NAME JQ_FILTER OP EXPECTED_JSON ARTIFACT",
        file=sys.stderr,
    )
    return 2


if __name__ == "__main__":
    argv = sys.argv[1:]
    if argv == ["--selftest"]:
        raise SystemExit(_selftest())
    if argv[:1] == ["--one"]:
        if len(argv) != 6:
            raise SystemExit(_usage())
        _name, _filter, _op, _expected_json, _artifact = argv[1:]
        try:
            _expected = json.loads(_expected_json)
        except ValueError as _exc:
            print(
                "  FAIL [%s]: expected=%s is not JSON: %s (UNRESOLVABLE, not "
                "contradicted)" % (_name, _expected_json, _exc)
            )
            raise SystemExit(EXIT_CODE[UNRESOLVABLE])
        raise SystemExit(run_one(_name, _filter, _op, _expected, _artifact))
    raise SystemExit(_usage())
'''


