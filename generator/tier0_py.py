def build_tier0_py(
    spec_id: str,
    arm: str,
    entries: list[Tier0Entry],
    step_note: str = "",
) -> str:
    """tests/tier0.py for one arm (and, for a multi-step task, one step)."""
    lines: list[str] = []
    for entry in entries:
        # The DECLARED path above the filter it compiled to: the reviewer's job
        # on this file is to see that the two ask the same question. Unwrapped
        # even when it is long -- a path broken across lines cannot be grepped
        # for or pasted back into the spec.
        lines.append("    # %s" % entry.jsonpath)
        lines.append("    (%r," % entry.name)
        lines.append("     %r," % entry.jq_filter)
        lines.append("     %r, %r)," % (entry.op, entry.expected))
    table = "\n".join(lines) + ("\n" if lines else "")
    header = (
        _TIER0_PY_HEADER.replace("__SPEC_ID__", spec_id)
        .replace("__ARM__", arm)
        .replace("__STEP_NOTE__", step_note)
    )
    return header + table + _TIER0_PY_TAIL

